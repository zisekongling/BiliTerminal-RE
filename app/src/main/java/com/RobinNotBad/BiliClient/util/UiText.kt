    /**
     * 带占位符的版本：`UiText.fmt("共%1\$s张图片", n)`。
     *
     * 用于「一句话中间夹个数」的拼接场景——原先是 `"共" + n + "张图片"`，只把前半段收进资源的话，
     * 后半句仍留在代码里，改写时会漏；换成一条 `%1\$s` 模板就只有一个落点。
     * 命中映射时按资源值格式化，没命中就按原文格式化（原文里没有 `%` 时原样返回）。
     */
    @JvmStatic
    fun fmt(raw: String, vararg args: Any?): String {
        val template = of(raw)
        if (template.indexOf('%') < 0) return template
        return try {
            java.lang.String.format(java.util.Locale.getDefault(), template, *args)
        } catch (e: Exception) {
            template
        }
    }

    /** 取显示文案；没登记就原样返回。`BiliTerminal.context` 为空（单测 / 崩溃进程）时也原样返回。 */
    @JvmStatic
    fun of(raw: String): String {
        if (raw.isEmpty()) return raw
        val res = MAP[raw] ?: return raw
        val context = BiliTerminal.context ?: return raw
        return context.getString(res)
    }
